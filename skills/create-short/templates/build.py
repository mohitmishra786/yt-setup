"""__TITLE__ — vertical Short built on the scene kit.

Generated by skills/create-short/scripts/scaffold.py. Out of the box this renders a ROUGH CUT:
each outline slide becomes a centred card with its `visual_beat`, plus notes and captions.
Replace scenes one at a time with real ones (skills/create-short/references/compose.md;
complete example: skills/create-short/examples/kernel-stack/build.py) and register them in
SCENES. Beat times come from ../cues.json (`cli.py cues`), never typed by hand.

Run from projects/<id>/composition:   ../../../.venv/bin/python build.py
"""

from __future__ import annotations

import json
import sys
