SCENES: dict[int, Callable[[dict], Scene]] = {
    # 1: scene1,
}


def main() -> None:
    outline = json.loads((PROJECT / "outline.json").read_text())
    cues_file = PROJECT / "cues.json"
    cues = json.loads(cues_file.read_text()) if cues_file.exists() else {}
    durs = json.loads((PROJECT / "audio" / "durations.json").read_text())["durations"]
    words = {int(sl["index"]): sl["words"]
             for sl in json.loads((PROJECT / "audio" / "words.json").read_text())["slides"]}
    slides = outline["slides"]
    seq = [(title_card(cues, TITLE, TITLE_S), TITLE_S, None, 0.0)]
    for k, slide in enumerate(slides, start=1):
        n = int(slide["index"])
        build = SCENES.get(n)
        scene = build(cues) if build else rough_scene(n, cues, slide)
        scene.add_notes(None, NOTES.get(n, [(0.0, slide["title"])]))
        scene.add_captions(words[n])
        hold = LAST_HOLD if k == len(slides) else 0.0
        seq.append((scene, durs[k - 1] + PAD + hold, n, durs[k - 1]))
    seq.append((outro(cues, OUTRO_S), OUTRO_S, None, 0.0))
    total = write_index(HERE, seq, TITLE)
    rough = [int(s["index"]) for s in slides if int(s["index"]) not in SCENES]
    print(f"built {len(seq)} scenes, total {total:.2f}s"
          + (f"  (rough-cut placeholders: slides {rough})" if rough else ""))


if __name__ == "__main__":
    main()
