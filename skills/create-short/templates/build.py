from pathlib import Path

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parent


def _kit_dir() -> Path:
    """The shared scene kit lives in the repo at skills/create-video/assets/."""
    for base in (HERE, *HERE.parents):
        kit = base / "skills" / "create-video" / "assets"
        if (kit / "scenekit.py").exists():
            return kit
    sys.exit("scenekit.py not found: this Short must live inside the yt-setup repo "
             "(projects/<id>/composition). https://github.com/mohitmishra786/yt-setup")


sys.path.insert(0, str(_kit_dir()))
from scenekit import K, Scene, outro, set_layout, title_card, write_index  # noqa: E402,F401

set_layout("portrait")
TITLE = "__TITLE__"
PAD, TITLE_S, OUTRO_S, LAST_HOLD = 0.6, 1.8, 2.5, 0.8
X, PW = 90, 900                       # content column: x 90..990

# One explanatory line per beat, keyed by outline slide index. A note that would show for
# under 1.2s is dropped automatically, so anchor them to beats ~1.5s+ apart.
# Example: NOTES[1] = [(0.0, "A tiny C program"), ("s1_free", "free(p) hands the memory back…")]
NOTES: dict[int, list[tuple[str | float, str]]] = {}


def rough_scene(n: int, cues: dict, slide: dict) -> Scene:
    """Placeholder until the real scene exists: the slide's visual_beat, centred."""
    s = Scene(n, cues)
    f = s.focus([300])
    s.box("card", X, f.y(0), PW, 300, slide.get("visual_beat") or slide["title"], kind="panel",
          size=38, weight=500, color=K["ink2"], extra="padding:32px;")
    f.run(["card"], [0.05])
    return s


